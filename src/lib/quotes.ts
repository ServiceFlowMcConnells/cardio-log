/** The same line all day, a new one tomorrow: steps through the list by date. */
export function dailyQuote(d = new Date()): string {
  const day = Math.floor(Date.UTC(d.getFullYear(), d.getMonth(), d.getDate()) / 86400000);
  // a fixed stride that is coprime with the list length, so neighbouring days don't get neighbouring lines
  const i = (day * 37) % QUOTES.length;
  return QUOTES[i];
}
